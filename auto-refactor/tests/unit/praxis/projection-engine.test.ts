/**
 * Module: Unit Test — Praxis LayerVFS Physical Projection Engine
 * File Path: tests/unit/praxis/projection-engine.test.ts
 * Architecture Role: Verifies the physical filesystem projection, confined command execution,
 *   bidirectional file synchronization, and host workspace isolation guarantees of LayerVFS.
 * Dependencies & Triggers: Consumes src/core/praxis/vfs, projection-engine, and vitest runner.
 * Responsibilities: Prove that virtual files materialize on disk, OS commands execute strictly
 *   inside projected sandboxes, modified physical files sync back into virtual branches, and
 *   host repository remains completely clean.
 * Exit Semantics & Design Rationale: Exits green when all assertions pass without error.
 */

import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import * as os from 'os';
import {
    createWorkspaceManager,
    projectWorkspace,
    WorkspaceManager,
} from '../../../src/core/praxis/vfs';

describe('LayerVFS — Physical Projection Engine & Sandbox Runner', () => {
    let tempDir: string;
    let manager: WorkspaceManager;

    beforeEach(() => {
        tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'layervfs-proj-test-'));
        manager = createWorkspaceManager();
    });

    afterEach(async () => {
        await manager.close();
        try {
            fs.rmSync(tempDir, { recursive: true, force: true });
        } catch {
            /* ignore cleanup */
        }
    });

    it('materializes virtual files into an isolated physical directory', async () => {
        const ws = await manager.createWorkspace({
            cardId: 'CARD-PROJ-1',
            cellId: 'cell-projection',
            agentUid: 'agent-projector',
        });

        await ws.putFile('src/calc.js', 'module.exports = { multiply: (a, b) => a * b };\n');
        await ws.putFile('package.json', '{"name":"projected-sample"}\n');

        const sandbox = await projectWorkspace(ws, {
            targetDir: path.join(tempDir, 'sandbox-1'),
            cleanOnClose: true,
        });

        expect(fs.existsSync(sandbox.projectedPath)).toBe(true);
        expect(fs.existsSync(path.join(sandbox.projectedPath, 'src', 'calc.js'))).toBe(true);
        expect(fs.existsSync(path.join(sandbox.projectedPath, 'package.json'))).toBe(true);

        const readContent = fs.readFileSync(
            path.join(sandbox.projectedPath, 'src', 'calc.js'),
            'utf8',
        );
        expect(readContent).toContain('multiply: (a, b) => a * b');

        await sandbox.close();
        expect(fs.existsSync(sandbox.projectedPath)).toBe(false);
    });

    it('executes real node command confined to sandbox directory with exit code 0', async () => {
        const ws = await manager.createWorkspace({
            cardId: 'CARD-PROJ-RUNNER',
            cellId: 'cell-runner',
            agentUid: 'agent-runner',
        });

        await ws.putFile(
            'run.js',
            'const fs = require("fs"); console.log("CWD=" + process.cwd()); fs.writeFileSync("output.txt", "DONE");\n',
        );

        const sandbox = await projectWorkspace(ws, {
            targetDir: path.join(tempDir, 'sandbox-runner'),
            cleanOnClose: true,
        });

        const execResult = await sandbox.runCommand('node', ['run.js']);

        expect(execResult.success).toBe(true);
        expect(execResult.exitCode).toBe(0);
        expect(execResult.stdout).toContain('CWD=');
        expect(execResult.stdout).toContain(sandbox.projectedPath);

        // Verify output file generated by script in physical sandbox
        expect(fs.existsSync(path.join(sandbox.projectedPath, 'output.txt'))).toBe(true);

        // Sync from physical back to virtual workspace branch
        const deltas = await sandbox.syncFromPhysical();
        const deltaPaths = deltas.map((d) => d.path);
        expect(deltaPaths).toContain('output.txt');
        expect(deltaPaths).toContain('run.js');

        const outputDelta = deltas.find((d) => d.path === 'output.txt');
        expect(outputDelta?.status).toBe('added');

        const virtualOutputFile = await ws.getFile('output.txt');
        expect(virtualOutputFile).not.toBeNull();
        expect(Buffer.from(virtualOutputFile!.content).toString()).toBe('DONE');

        await sandbox.close();
    });

    it('enforces execution timeout when command exceeds deadline', async () => {
        const ws = await manager.createWorkspace({
            cardId: 'CARD-TIMEOUT-TEST',
            cellId: 'cell-timeout',
            agentUid: 'agent-slow',
        });

        await ws.putFile('hang.js', 'setInterval(() => {}, 1000);\n');

        const sandbox = await projectWorkspace(ws, {
            targetDir: path.join(tempDir, 'sandbox-timeout'),
            cleanOnClose: true,
        });

        // Timeout set to 300ms
        const execResult = await sandbox.runCommand('node', ['hang.js'], { timeoutMs: 300 });

        expect(execResult.success).toBe(false);
        expect(execResult.exitCode).toBe(124);
        expect(execResult.errorMessage).toContain('timed out');

        await sandbox.close();
    });
});
